"""Write the readable reports from the saved evaluation runs.

Usage:
    python -m eval.report            write SUMMARY.md and ERRORS.md
    python -m eval.report --check    fail if either file is out of date

Both files are generated from the JSON result files in ``eval/results``. They
are never edited by hand, so a number in them can always be traced to a run.
This module makes no model calls and needs nothing but the standard library.
"""

from __future__ import annotations

import argparse
import json
from collections import defaultdict
from collections.abc import Mapping, Sequence
from pathlib import Path
from typing import Any

from eval.stats import percentile, rate_with_interval

RESULTS_DIR = Path("eval/results")
SUMMARY_FILE = RESULTS_DIR / "SUMMARY.md"
ERRORS_FILE = RESULTS_DIR / "ERRORS.md"
INSPECTED_FILE = RESULTS_DIR / "inspected.json"

_PASS_VALUES = {"yes", "true", "pass"}
_FAIL_VALUES = {"no", "false", "fail"}

# (column heading, scorer) for the rates in the summary table.
RATE_COLUMNS: tuple[tuple[str, str], ...] = (
    ("Source retrieved", "expected_source_retrieved"),
    ("Context sufficient", "retrieval_sufficiency"),
    ("Grounded", "retrieval_groundedness"),
    ("Correct", "correctness"),
    ("Relevant", "relevance_to_query"),
    ("Rules followed", "expectations_guidelines"),
    ("Reading level ok", "reading_level_ok"),
    ("Hand-off correct", "escalation_correct"),
    ("Right tool", "tool_choice"),
    ("No PII leak", "no_pii_leak"),
)
# Scorers that judge each retrieved chunk, not the answer. Most rows have a chunk
# that is off the point, so a "no" here is not a failed row. It is reported as a
# mean (chunk relevance) in the result file.
NOT_A_ROW_FAILURE = frozenset({"retrieval_relevance"})
# What a failed check says about the row, before anyone has read it.
CHECK_KINDS: dict[str, str] = {
    "expected_source_retrieved": "retrieval",
    "expected_source_cited": "retrieval",
    "retrieval_sufficiency": "retrieval",
    "retrieval_groundedness": "answer, by the judge",
    "correctness": "answer, by the judge",
    "relevance_to_query": "answer, by the judge",
    "expectations_guidelines": "answer, by the judge",
    "safety": "answer, by the judge",
    "reading_level_ok": "reading level",
    "escalation_correct": "routing",
    "tool_choice": "tool choice",
    "no_pii_leak": "personal data",
    "citation_valid": "citation",
    "answer_recorded": "no answer",
}
CATEGORY_NAMES: dict[str, str] = {
    "kb": "Help articles",
    "plan": "Plan lookups",
    "call_summary": "Call summaries",
    "escalation": "Requests that need a person",
    "adversarial": "Trick questions",
}

SUMMARY_INTRO = """\
# Evaluation runs

Generated by `python -m eval.report` from the JSON files in this folder. Do not edit it by hand.

One row per saved run. A rate is shown as passed/scored, then its 95% Wilson interval: the \
range the true rate plausibly lies in, given how few rows there are. `n/a` means the scorer \
was not run. Dates are UTC.

How to read it:

- **These sets are small.** A perfect 22/22 supports "at least about 85%", not "100%".
- **A column at its ceiling shows no failure was found, not that none is possible.** The \
judge's ability to catch a wrong answer has not been tested with deliberately wrong answers.
- **"Hand-off correct" is in-sample.** The routing rules were written with the five hand-off \
rows in view. The other rows are questions that should not be handed off.
- **"No PII leak" rests on one row** that plants personal data in the question, and the \
scorer uses the same redactor as the output check it is testing.
- **A run with `n/a` under the judged columns is a comparison between models**, scored \
by code and by the correctness judges only. The CI gate ignores those and reads the newest \
run that every judge scored.
- The `m3-kb` run is a draft, kept for the record. Its questions had not been reviewed, the \
help articles had not been corrected, and the grading has changed since, so it is not \
comparable with the rows after it.
"""

ERRORS_INTRO = """\
# Failed rows

Generated by `python -m eval.report` from the JSON files in this folder and from \
`inspected.json`. Do not edit it by hand.

Every row that failed a check, in every saved run. "Kind" is what the failed check measures. \
"Read by hand" says what was found when someone read the answer, and is empty when nobody \
did or the finding was not recorded against that row. A mark from the judge is reported as \
the judge gave it, even where reading the answer showed the judge was wrong.
"""


def as_pass(value: Any) -> bool | None:
    """Read a pass/fail value. Returns None for anything that is not pass/fail."""
    if isinstance(value, bool):
        return value
    if isinstance(value, str):
        lowered = value.strip().lower()
        if lowered in _PASS_VALUES:
            return True
        if lowered in _FAIL_VALUES:
            return False
    return None


def load_results(results_dir: Path = RESULTS_DIR) -> list[tuple[str, dict[str, Any]]]:
    """The saved agent evaluation runs as (file name, report), oldest first.

    Redaction results live in the same folder under ``redaction_*`` and have
    their own table in the README.
    """
    found: list[tuple[str, dict[str, Any]]] = []
    for path in sorted(results_dir.glob("*.json")):
        if path.name.startswith("redaction_") or path.name == INSPECTED_FILE.name:
            continue
        report = json.loads(path.read_text(encoding="utf-8"))
        if "per_row" in report and "metrics" in report:
            found.append((path.name, report))
    return sorted(found, key=lambda item: (item[1]["run_at"], item[0]))


def _rate(metrics: Mapping[str, Mapping[str, Any]], name: str) -> str:
    metric = metrics.get(name)
    if not metric or metric.get("kind") != "pass_fail":
        return "n/a"
    return rate_with_interval(int(metric["passed"]), int(metric["scored"]))


def _router(report: Mapping[str, Any]) -> str:
    """How requests were routed in a run. Runs from before the router used the rules."""
    if report.get("router", "rules") != "model":
        return "rules"
    return str(report.get("router_endpoint", "model")).removeprefix("databricks-")


def _latencies(rows: Sequence[Mapping[str, Any]]) -> list[float]:
    values = [row["scores"].get("latency_ms") for row in rows]
    return [float(value) / 1000 for value in values if isinstance(value, int | float)]


def _latency_cells(seconds: Sequence[float]) -> str:
    if not seconds:
        return "n/a | n/a | n/a"
    return f"{percentile(seconds, 0.5):.1f} | {percentile(seconds, 0.95):.1f} | {max(seconds):.1f}"


def summary_markdown(results: Sequence[tuple[str, Mapping[str, Any]]]) -> str:
    """The whole of ``SUMMARY.md``."""
    lines = [SUMMARY_INTRO, "## Runs", ""]
    headings = ["Date", "Tag", "Model", "Router", "Config", "Query", "Prompt", "Rows"]
    headings += ["Reviewed", "Figures in sources"]
    headings += [heading for heading, _ in RATE_COLUMNS]
    headings += ["Commit", "File"]
    lines.append("| " + " | ".join(headings) + " |")
    lines.append("|" + "---|" * len(headings))
    for file_name, report in results:
        metrics = report["metrics"]
        cells = [
            report["run_at"][:10],
            report["tag"],
            str(report.get("llm_endpoint", "n/a")).removeprefix("databricks-"),
            _router(report),
            report["chunk_config"],
            report["query_type"],
            str(report.get("prompt_version", "n/a")),
            str(report["rows"]),
            f"{report['rows_reviewed']}/{report['rows']}",
            _rate(metrics, "figures_supported"),
            *(_rate(metrics, scorer) for _, scorer in RATE_COLUMNS),
            f"`{report['git_sha'][:7]}`",
            file_name,
        ]
        lines.append("| " + " | ".join(cells) + " |")

    lines += [
        "",
        "## Time to answer",
        "",
        "Seconds from the question to the checked answer, one row at a time. The median hides "
        "the slow answers, so the 95th percentile and the slowest are shown too. Requests "
        "that need a person are answered by rules with no model call, which is why they "
        "are fast.",
        "",
        "| Run | Questions | Rows | Median | 95th percentile | Slowest |",
        "|---|---|---|---|---|---|",
    ]
    for file_name, report in results:
        by_category: dict[str, list[Mapping[str, Any]]] = defaultdict(list)
        for row in report["per_row"]:
            by_category[str(row.get("category", "kb"))].append(row)
        groups = [("All", list(report["per_row"]))]
        if len(by_category) > 1:
            groups += [
                (CATEGORY_NAMES.get(name, name), rows) for name, rows in sorted(by_category.items())
            ]
        for label, rows in groups:
            seconds = _latencies(rows)
            lines.append(f"| {file_name} | {label} | {len(seconds)} | {_latency_cells(seconds)} |")
    return "\n".join(lines) + "\n"


def failed_checks(scores: Mapping[str, Any]) -> list[str]:
    """The pass/fail checks a row failed, leaving out the per-chunk ones."""
    return sorted(
        name
        for name, value in scores.items()
        if name not in NOT_A_ROW_FAILURE and as_pass(value) is False
    )


def errors_markdown(
    results: Sequence[tuple[str, Mapping[str, Any]]],
    inspected: Mapping[str, Mapping[str, Mapping[str, str]]],
) -> str:
    """The whole of ``ERRORS.md``."""
    lines = [ERRORS_INTRO]
    for file_name, report in results:
        failed = [
            (row, failed_checks(row["scores"]))
            for row in report["per_row"]
            if failed_checks(row["scores"])
        ]
        lines += [
            f"## {file_name}",
            "",
            f"{len(failed)} of {report['rows']} rows failed at least one check. "
            f"Commit `{report['git_sha'][:7]}`, prompt {report.get('prompt_version', 'n/a')}.",
            "",
        ]
        if not failed:
            continue
        lines += [
            "| Row | Questions | Failed check | Kind | Read by hand |",
            "|---|---|---|---|---|",
        ]
        notes = inspected.get(file_name, {})
        for row, checks in failed:
            note = notes.get(row["id"])
            read = f"**{note['cause']}.** {note['found']}" if note else ""
            kinds = sorted({CHECK_KINDS.get(check, "other") for check in checks})
            category = str(row.get("category", "kb"))
            lines.append(
                f"| {row['id']} | {CATEGORY_NAMES.get(category, category)} | "
                f"{', '.join(checks)} | {'; '.join(kinds)} | {read} |"
            )
        lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n"


def build(results_dir: Path = RESULTS_DIR) -> dict[Path, str]:
    """The generated files and their text."""
    results = load_results(results_dir)
    inspected_path = results_dir / INSPECTED_FILE.name
    inspected = (
        json.loads(inspected_path.read_text(encoding="utf-8")) if inspected_path.exists() else {}
    )
    inspected = {name: rows for name, rows in inspected.items() if not name.startswith("_")}
    return {
        results_dir / SUMMARY_FILE.name: summary_markdown(results),
        results_dir / ERRORS_FILE.name: errors_markdown(results, inspected),
    }


def write(results_dir: Path = RESULTS_DIR) -> list[Path]:
    """Write the generated files. Returns the ones that changed."""
    changed: list[Path] = []
    for path, text in build(results_dir).items():
        if not path.exists() or path.read_text(encoding="utf-8") != text:
            path.write_text(text, encoding="utf-8", newline="\n")
            changed.append(path)
    return changed


def out_of_date(results_dir: Path = RESULTS_DIR) -> list[Path]:
    """The generated files whose text on disk is not what would be written now."""
    return [
        path
        for path, text in build(results_dir).items()
        if not path.exists() or path.read_text(encoding="utf-8") != text
    ]


def main(argv: list[str] | None = None) -> None:
    """Write the reports, or with ``--check`` fail if they are out of date."""
    parser = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    parser.add_argument("--check", action="store_true", help="fail if a report is out of date")
    args = parser.parse_args(argv)
    if args.check:
        stale = out_of_date()
        for path in stale:
            print(f"out of date: {path.as_posix()} (run python -m eval.report)")
        raise SystemExit(1 if stale else 0)
    for path in write():
        print(f"wrote {path.as_posix()}")


if __name__ == "__main__":
    main()
